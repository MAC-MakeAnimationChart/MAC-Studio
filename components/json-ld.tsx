// Puts structured data (schema.org JSON-LD) into the page for search engines. Server component.
// "<" is escaped so that text inside the data can never close the script tag.
export function JsonLd({ data }: { data: Record<string, unknown> }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, "\\u003c"),
      }}
    />
  );
}
